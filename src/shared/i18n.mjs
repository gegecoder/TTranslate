// ---- 当前语言状态（每个 JS 上下文各持一份） ----------------------------------
const SUPPORTED_LANGS = ['en', 'zh', 'zh-TW', 'ja', 'ko', 'fr', 'de', 'es', 'ru'];
const HTML_LANG = {
  en: 'en', zh: 'zh-CN', 'zh-TW': 'zh-TW',
  ja: 'ja', ko: 'ko', fr: 'fr', de: 'de', es: 'es', ru: 'ru',
};
// 自动检测选项在各语言下的文案（Intl.DisplayNames 不支持 'auto'）
const AUTO_LABEL = {
  en: 'Auto', zh: '自动检测', 'zh-TW': '自動偵測',
  ja: '自動検出', ko: '자동 감지', fr: 'Détection automatique',
  de: 'Automatisch erkennen', es: 'Detección automática', ru: 'Автоопределение',
};
// 音标区域标签：有道返回 '英' / '美'
const REGION_LABEL = {
  en: { 英: 'UK', 美: 'US' },
  ja: { 英: '英', 美: '米' },
  ko: { 英: '영', 美: '미' },
  fr: { 英: 'UK', 美: 'US' },
  de: { 英: 'UK', 美: 'US' },
  es: { 英: 'UK', 美: 'US' },
  ru: { 英: 'UK', 美: 'US' },
};

let currentLang = 'zh';

/** 把配置值（auto 或语言代码）解析成实际语言 */
export function resolveUiLang(setting) {
  if (SUPPORTED_LANGS.includes(setting)) return setting;
  const nav = String(typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  if (nav.startsWith('zh')) return /zh-(tw|hk|mo)/.test(nav) ? 'zh-TW' : 'zh';
  for (const code of ['ja', 'ko', 'fr', 'de', 'es', 'ru']) {
    if (nav.startsWith(code)) return code;
  }
  return 'en';
}

/** 设置当前界面的语言（非法值回退中文） */
export function setUiLang(lang) {
  currentLang = SUPPORTED_LANGS.includes(lang) ? lang : 'zh';
}

export function getUiLang() {
  return currentLang;
}

/**
 * 取词条，例如 t('popup.page.translate')。
 * 查找顺序：当前语言包 → 英文 → 中文 → key 本身。
 * vars 形如 { n: 3 }，替换文案里的 {n} 占位。
 */
export function t(key, vars) {
  const item = MESSAGES[key];
  let text;
  if (currentLang === 'zh') text = item?.zh;
  else if (currentLang === 'en') text = item?.en ?? item?.zh;
  else text = PACKS[currentLang]?.[key] ?? item?.en ?? item?.zh;
  if (text == null) text = key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/** 音标区域标签本地化：'英'/'美' → 当前界面语言对应的写法 */
export function regionLabel(region) {
  if (!region) return '';
  return REGION_LABEL[currentLang]?.[region] ?? region;
}

// Intl.DisplayNames 缓存（按界面语言各建一个实例）
let displayNames = { lang: null, dn: null };

/** 语言名本地化（翻译语言下拉的选项文案） */
export function langLabel(l) {
  if (l.code === 'auto') return AUTO_LABEL[currentLang] || l.labelEn || l.label;
  if (currentLang === 'zh') return l.label;
  try {
    if (displayNames.lang !== currentLang) {
      displayNames = {
        lang: currentLang,
        dn: new Intl.DisplayNames([HTML_LANG[currentLang] || 'en'], { type: 'language' }),
      };
    }
    const name = displayNames.dn.of(l.code);
    if (name) return name;
  } catch { /* 环境不支持 Intl.DisplayNames 时回退英文名 */ }
  return l.labelEn || l.label;
}

/** 服务名本地化 */
export function serviceName(svc) {
  return currentLang === 'zh' || currentLang === 'zh-TW'
    ? svc.name
    : (svc.nameEn || svc.name);
}

// ---- 静态 DOM 应用（根目录 index.html 同款「中文原文 → key」反查） --------------
const SKIP = /^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/;
const ZH_TO_KEY = {};   // 归一化中文原文 → key
let textNodes = [];     // { node, lead, tail, raw, key }
let attrNodes = [];     // { el, attr, raw, key }
let collected = false;

for (const [key, item] of Object.entries(MESSAGES)) {
  if (item.zh && !ZH_TO_KEY[normalize(item.zh)]) ZH_TO_KEY[normalize(item.zh)] = key;
}

function normalize(raw) {
  return raw.replace(/\s+/g, ' ').trim();
}

/** 收集 root 下所有命中词条的文本节点与 title/placeholder/aria-label 属性（只做一次） */
export function collectStaticI18n(root = document.body) {
  if (collected) return;
  collected = true;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      if (!node.parentNode || SKIP.test(node.parentNode.nodeName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  let node;
  while ((node = walker.nextNode())) {
    const raw = node.nodeValue;
    const m = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const key = ZH_TO_KEY[normalize(m[2])];
    if (!key) continue;
    textNodes.push({ node, lead: m[1], tail: m[3], raw, key });
  }

  root.querySelectorAll('[title], [placeholder], [aria-label]').forEach((el) => {
    for (const attr of ['title', 'placeholder', 'aria-label']) {
      const raw = el.getAttribute(attr);
      if (!raw) continue;
      const key = ZH_TO_KEY[normalize(raw)];
      if (key) attrNodes.push({ el, attr, raw, key });
    }
  });
}

/** 应用界面语言到已收集的静态节点（并更新 <html lang>） */
export function applyStaticI18n() {
  // 中文是原文，直接恢复收集时保存的原始文本
  const useRaw = currentLang === 'zh';
  for (const item of textNodes) {
    node_setValue(item, useRaw ? null : t(item.key));
  }
  for (const item of attrNodes) {
    item.el.setAttribute(item.attr, useRaw ? item.raw : t(item.key));
  }
  document.documentElement.lang = HTML_LANG[currentLang] || 'en';
}

function node_setValue(item, value) {
  item.node.nodeValue = value != null ? item.lead + value + item.tail : item.raw;
}
